const defaultLanguage = "en";
const languageStorageKey = "personal-homepage-language";
let currentLanguage = defaultLanguage;

const emailCopyLinks = document.querySelectorAll("[data-copy-email]");
const copyStatus = document.querySelector("[data-copy-status]");
const viewButtons = document.querySelectorAll("[data-view-target]");
const contentPanels = document.querySelectorAll("[data-content-panel]");
const languageButtons = document.querySelectorAll("[data-language]");
const postsPanel = document.getElementById("posts-panel");
const postListView = document.querySelector("[data-post-list-view]");
const postArticles = document.querySelectorAll("[data-post-article]");
let copyStatusTimerId;

const panelHashes = {
  "home-panel": "#home",
  "info-panel": "#info",
  "posts-panel": "#posts",
};

function translate(key) {
  return translations[currentLanguage][key] ?? translations.en[key] ?? "";
}

function updateTranslatedText() {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      translate(element.dataset.i18nAriaLabel),
    );
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", translate(element.dataset.i18nTitle));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", translate(element.dataset.i18nAlt));
  });

  document.documentElement.lang = currentLanguage === "ko" ? "ko" : "en";
  document.title = translate("meta.title");
  document
    .querySelector('meta[name="description"]')
    ?.setAttribute("content", translate("meta.description"));
  document
    .querySelector('meta[property="og:title"]')
    ?.setAttribute("content", translate("meta.title"));
  document
    .querySelector('meta[property="og:description"]')
    ?.setAttribute("content", translate("meta.ogDescription"));
}

function updateLanguageButtons() {
  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem(languageStorageKey, language);
  } catch {
    // Ignore storage failures; the visible language still changes.
  }
}

function getSavedLanguage() {
  try {
    return window.localStorage.getItem(languageStorageKey);
  } catch {
    return null;
  }
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : defaultLanguage;
  updateTranslatedText();
  updateLanguageButtons();
  emailCopyLinks.forEach((emailCopyLink) => {
    emailCopyLink.classList.remove("is-copied");
  });

  if (copyStatus) {
    window.clearTimeout(copyStatusTimerId);
    copyStatus.textContent = "";
    copyStatus.classList.remove("is-visible", "is-error");
  }

  saveLanguage(currentLanguage);
}

function showCopyStatus(message, isError = false) {
  if (!copyStatus) {
    return;
  }

  window.clearTimeout(copyStatusTimerId);
  copyStatus.textContent = message;
  copyStatus.classList.toggle("is-error", isError);
  copyStatus.classList.add("is-visible");

  copyStatusTimerId = window.setTimeout(
    () => {
      copyStatus.classList.remove("is-visible", "is-error");
      copyStatus.textContent = "";
    },
    isError ? 3200 : 2200,
  );
}

function getPostArticleFromHash() {
  const currentHash = window.location.hash.toLowerCase();
  return Array.from(postArticles).find(
    (article) => `#posts/${article.dataset.postArticle}` === currentHash,
  );
}

function getPanelIdFromHash() {
  const currentHash = window.location.hash.toLowerCase();
  if (currentHash.startsWith("#posts/")) {
    return "posts-panel";
  }
  return (
    Object.keys(panelHashes).find(
      (panelId) => panelHashes[panelId] === currentHash,
    ) ?? "home-panel"
  );
}

function showContentPanel(panelId, updateUrl = true) {
  const resolvedPanelId = panelHashes[panelId] ? panelId : "home-panel";

  contentPanels.forEach((panel) => {
    const isActive = panel.id === resolvedPanelId;
    panel.hidden = !isActive;
    panel.classList.toggle("is-active", isActive);
  });

  viewButtons.forEach((button) => {
    const isActive = button.dataset.viewTarget === resolvedPanelId;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-selected", String(isActive));
    button.tabIndex = isActive ? 0 : -1;
  });

  const nextHash = panelHashes[resolvedPanelId];

  if (updateUrl && window.location.hash !== nextHash) {
    window.history.pushState(null, "", nextHash);
  }

  const activePost =
    resolvedPanelId === "posts-panel" ? getPostArticleFromHash() : undefined;

  if (postListView) {
    postListView.hidden = Boolean(activePost);
  }

  postArticles.forEach((article) => {
    article.hidden = article !== activePost;
  });

  postsPanel?.setAttribute(
    "aria-labelledby",
    activePost?.getAttribute("aria-labelledby") ?? "posts-title",
  );
}

viewButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const panelId = button.dataset.viewTarget;

    if (panelId) {
      showContentPanel(panelId);
    }
  });
});

viewButtons.forEach((button, index) => {
  button.addEventListener("keydown", (event) => {
    let nextIndex;

    if (event.key === "ArrowRight" || event.key === "ArrowDown") {
      nextIndex = (index + 1) % viewButtons.length;
    } else if (event.key === "ArrowLeft" || event.key === "ArrowUp") {
      nextIndex = (index - 1 + viewButtons.length) % viewButtons.length;
    } else if (event.key === "Home") {
      nextIndex = 0;
    } else if (event.key === "End") {
      nextIndex = viewButtons.length - 1;
    } else {
      return;
    }

    event.preventDefault();
    const nextButton = viewButtons[nextIndex];
    nextButton.focus();

    if (nextButton.dataset.viewTarget) {
      showContentPanel(nextButton.dataset.viewTarget);
    }
  });
});

function syncPanelWithUrl(event) {
  const previousPost = Array.from(postArticles).find((article) => !article.hidden);
  showContentPanel(getPanelIdFromHash(), false);

  if (!event) {
    return;
  }

  const activePost = getPostArticleFromHash();
  if (activePost) {
    activePost.querySelector("h2")?.focus({ preventScroll: true });
  } else if (previousPost && getPanelIdFromHash() === "posts-panel") {
    postListView
      ?.querySelector(`a[href="#posts/${previousPost.dataset.postArticle}"]`)
      ?.focus({ preventScroll: true });
  }
}

window.addEventListener("popstate", syncPanelWithUrl);
window.addEventListener("hashchange", syncPanelWithUrl);

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.language);
  });
});

async function copyText(text) {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return;
    } catch {
      // Fall back for browsers that expose the API but block it by policy.
    }
  }

  const textArea = document.createElement("textarea");
  textArea.value = text;
  textArea.setAttribute("readonly", "");
  textArea.setAttribute("aria-hidden", "true");
  textArea.style.position = "fixed";
  textArea.style.top = "-999px";
  textArea.style.left = "-999px";
  document.body.append(textArea);
  textArea.focus();
  textArea.select();
  textArea.setSelectionRange(0, text.length);

  try {
    const copied = document.execCommand("copy");
    if (!copied) {
      throw new Error("Copy command failed");
    }
  } finally {
    textArea.remove();
  }
}

emailCopyLinks.forEach((emailCopyLink) => {
  emailCopyLink.addEventListener("click", async (event) => {
    event.preventDefault();

    const email = emailCopyLink.dataset.copyEmail;

    if (!email) {
      return;
    }

    try {
      await copyText(email);
      emailCopyLink.classList.add("is-copied");

      showCopyStatus(
        translate("copy.success").replace("{email}", email),
      );

      window.setTimeout(() => {
        emailCopyLink.classList.remove("is-copied");
      }, 1400);
    } catch {
      showCopyStatus(translate("copy.error"), true);
    }
  });
});

