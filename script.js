function translate(key) {
  return translations[currentLanguage][key] ?? translations.en[key] ?? "";
}

function updatePostEpisodeTitles() {
  postArticles.forEach((article) => {
    const episode = article.dataset.postEpisode;
    const heading = article.querySelector("h2[data-i18n]");

    if (!heading || !/^[1-9]\d*$/.test(episode ?? "")) {
      return;
    }

    const title = `ep. ${episode} ${translate(heading.dataset.i18n)}`;
    heading.textContent = title;

    const listLink = postListView?.querySelector(
      `a[href="#posts/${article.dataset.postArticle}"]`,
    );
    if (listLink) {
      listLink.textContent = title;
      listLink.title = title;
    }
  });
}

function updateTranslatedText() {
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      translate(element.dataset.i18nAriaLabel),
    );
  });

  document.querySelectorAll("[data-i18n-title]").forEach((element) => {
    element.setAttribute("title", translate(element.dataset.i18nTitle));
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.setAttribute("alt", translate(element.dataset.i18nAlt));
  });

  updatePostEpisodeTitles();

  document.documentElement.lang = currentLanguage === "ko" ? "ko" : "en";
  document.title = translate("meta.title");
  document
    .querySelector('meta[name="description"]')
    ?.setAttribute("content", translate("meta.description"));
  document
    .querySelector('meta[property="og:title"]')
    ?.setAttribute("content", translate("meta.title"));
  document
    .querySelector('meta[property="og:description"]')
    ?.setAttribute("content", translate("meta.ogDescription"));
}

function updateLanguageButtons() {
  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
}

function saveLanguage(language) {
  try {
    window.localStorage.setItem(languageStorageKey, language);
  } catch {
    // Ignore storage failures; the visible language still changes.
  }
}

function getSavedLanguage() {
  try {
    return window.localStorage.getItem(languageStorageKey);
  } catch {
    return null;
  }
}

function setLanguage(language) {
  currentLanguage = translations[language] ? language : defaultLanguage;
  updateTranslatedText();
  updateLanguageButtons();
  emailCopyLinks.forEach((emailCopyLink) => {
    emailCopyLink.classList.remove("is-copied");
  });

  if (copyStatus) {
    window.clearTimeout(copyStatusTimerId);
    copyStatus.textContent = "";
    copyStatus.classList.remove("is-visible", "is-error");
  }

  saveLanguage(currentLanguage);
}

function showCopyStatus(message, isError = false) {
  if (!copyStatus) {
    return;
  }

  window.clearTimeout(copyStatusTimerId);
  copyStatus.textContent = message;
  copyStatus.classList.toggle("is-error", isError);
  copyStatus.classList.add("is-visible");

  copyStatusTimerId = window.setTimeout(
    () => {
      copyStatus.classList.remove("is-visible", "is-error");
      copyStatus.textContent = "";
    },
    isError ? 3200 : 2200,
  );
}

